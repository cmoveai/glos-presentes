export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return PRODUCTS.filter(
    (p) => p.id !== product.id && (p.category === product.category || p.isKit === product.isKit)
  ).slice(0, limit);
}

export function getBestsellers(limit = 8): Product[] {
  return PRODUCTS.filter((p) => p.bestseller).slice(0, limit);
}

export function getNewArrivals(limit = 8): Product[] {
  return PRODUCTS.filter((p) => p.new || p.featured).slice(0, limit);
}

export function getGiftKits(limit = 6): Product[] {
  return PRODUCTS.filter((p) => p.isKit || p.category === "kits-presenteaveis").slice(0, limit);
}
